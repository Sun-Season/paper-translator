"""中文论文翻译和复核共用的语言要求。"""

CHINESE_PROSE_POLICY = """中文论文译文要同时做到信、达、雅。忠实传达事实和论证，用自然的中文把意思说清楚，措辞符合科研语体。
拆。读完原段，再找出研究对象、动作、数据来源、条件和结论。长句先按意群拆开，区分主张、证据和限制。保持原有段落和论证关系。
调。按中文习惯组织句子。过长的定语或从句可以单独成句。原文能确定施事者时，可以用主动句。施事者不明时，可以省略主语或保留被动。调整后核对条件、否定、比较对象、先后关系、适用范围和确定程度。
增。为了衔接，可以补出原文已经明确的对象、范畴词和逻辑关系。只有指代明确时才换成具体名词。若原文允许多种理解，保留歧义。推测仍是推测，相关仍是相关。相邻页提示只帮助理解当前页的指代、术语和续句。
转。能用准确的动词说清楚时，把英文的抽象名词或层层修饰改成动作和对象。避免照搬英文被动句和反复使用「通过」「进行」「其」。遇到重复介词，分清它们分别表示路径、工具还是来源。比如描述梯度时，说清沿哪条轨迹反向传播、用哪个模型求梯度。学术表述简洁得体，保留必要的专业术语。
先判断术语在原文中的含义，再在全文统一译名。举例说明：在强化学习和仿真中，transition 指状态转移，logged simulator transitions 是模拟器记录的状态转移数据。rollout 依语境译为推演或轨迹，模型中的 imagined rollout 可译为模型推演。learned model 是学习得到的模型，learnable model 才是可学习的模型。遇到 amortize learning，写清哪些动作复用同一个模型或如何分摊学习成本。术语示例只适用于对应语境。
按既有规则保留方法名称、缩写、代码标识、数字、单位、引用和公式。交付前先对照原文逐项核对术语、事实、限制和语气，再单独连读中文，改掉妨碍理解的语序和重复结构。保持信息完整，只按要求输出译文。"""

PROSE_REVIEW_POLICY = """正文译文同时检查准确性、可读性和流畅度。对照完整原段。确有跨页衔接时结合相邻原文。
查术语是否符合学科语境。同一概念在所给上下文中应使用一致译名。核对被补出的施事者、指代和因果能否从原文确定，并确认拆句后条件仍限定原来的主张。
查机械直译是否使对象、指代、条件、比较或句间关系难以辨认。报告时引用原文和可定位的译文，说明读者会在哪里读不清或误解，并提出能恢复理解的最小改写。保留原文的事实、条件、结论和确定程度。通顺准确的同义译法可直接通过。"""


def chinese_prose_policy(target):
    if target.lower().startswith("zh"):
        return "\n\n" + CHINESE_PROSE_POLICY
    return ""
